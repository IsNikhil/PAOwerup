import { api, downloadBlob } from './api'
import type { CoachResponse, FeedbackResponse, MatchResponse, ResumeDoc } from './types'

export async function downloadResumeDocx(doc: ResumeDoc) {
  const { blob, filename } = await api.rewriteDocx(doc)
  downloadBlob(blob, filename)
}

export function resumeToMarkdown(doc: ResumeDoc): string {
  const lines = [`# ${doc.name}`, doc.headline && `_${doc.headline}_`, doc.contact, '', doc.summary && `## Summary\n${doc.summary}`]
  for (const s of doc.sections) {
    lines.push(`\n## ${s.title}`)
    for (const it of s.items) {
      if (it.heading) lines.push(`**${it.heading}**${it.subheading ? ` — ${it.subheading}` : ''}${it.dates ? ` (${it.dates})` : ''}`)
      for (const b of it.bullets) lines.push(`- ${b}`)
    }
  }
  if (doc.skills.length) lines.push(`\n## Skills\n${doc.skills.join(', ')}`)
  if (doc.skills_to_develop.length) lines.push(`\n## Skills to develop\n${doc.skills_to_develop.join(', ')}`)
  return lines.filter((l): l is string => typeof l === 'string' && l !== '').join('\n')
}

export function reportSummaryText(m?: MatchResponse, coach?: CoachResponse, fb?: FeedbackResponse): string {
  const out: string[] = ['PAOwerUp Career Report']
  if (m) {
    out.push(`Match score: ${m.score.toFixed(0)}/100 (${m.verdict})`, m.summary)
    out.push(`Matched: ${m.matched_skills.map((s) => s.name).join(', ') || '—'}`)
    out.push(`Missing: ${m.missing_skills.map((s) => s.name).join(', ') || '—'}`)
  }
  if (coach) out.push('', 'Next steps:', ...coach.steps.map((s, i) => `${i + 1}. ${s.title} — ${s.detail}`))
  if (fb) out.push('', `Interview rating: ${fb.rating}/10`, fb.overall)
  return out.join('\n')
}

const esc = (s: string) => s.replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c]!)

/** Opens a print-ready report in a new window; the browser's "Save as PDF" does the rest. */
export function printReport(title: string, m?: MatchResponse, coach?: CoachResponse, fb?: FeedbackResponse, resume?: ResumeDoc) {
  const w = window.open('', '_blank', 'width=900,height=1100')
  if (!w) return false
  const chips = (xs: string[], cls: string) => xs.map((x) => `<span class="chip ${cls}">${esc(x)}</span>`).join(' ')
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>${esc(title)} – PAOwerUp report</title>
<style>
body{font-family:-apple-system,Inter,Segoe UI,sans-serif;color:#18181b;max-width:760px;margin:40px auto;padding:0 24px;line-height:1.5}
h1{font-size:22px;margin:0}h2{font-size:14px;text-transform:uppercase;letter-spacing:.08em;color:#52525b;border-bottom:1px solid #e4e4e7;padding-bottom:4px;margin-top:28px}
.score{font-size:56px;font-weight:600;letter-spacing:-.03em}.muted{color:#71717a}.chip{display:inline-block;border-radius:99px;padding:2px 9px;margin:2px;font-size:12px}
.ok{background:#dcfce7;color:#166534}.miss{background:#fee2e2;color:#991b1b}li{margin:4px 0}
</style></head><body>
<h1>${esc(title)}</h1><div class="muted">Generated by PAOwerUp Careers · ${new Date().toLocaleString()}</div>
${m ? `<h2>Match</h2><div class="score">${m.score.toFixed(0)}<span class="muted" style="font-size:20px">/100</span></div><div>${esc(m.verdict)} — ${esc(m.summary)}</div>
<p>Skill coverage ${Math.round(m.breakdown.skill_coverage * 100)}% · Sentence similarity ${Math.round(m.breakdown.sentence_similarity * 100)}% · Document similarity ${Math.round(m.breakdown.document_similarity * 100)}%</p>
<p><b>Matched</b><br>${chips(m.matched_skills.map((s) => s.name), 'ok')}</p><p><b>Missing</b><br>${chips(m.missing_skills.map((s) => s.name), 'miss')}</p>` : ''}
${coach ? `<h2>Next steps</h2><p>${esc(coach.headline)}</p><ol>${coach.steps.map((s) => `<li><b>${esc(s.title)}</b> (${esc(s.timeframe)}) — ${esc(s.detail)}</li>`).join('')}</ol>` : ''}
${fb ? `<h2>Interview</h2><p><b>${fb.rating}/10</b> — ${esc(fb.overall)}</p><p><b>Strengths</b></p><ul>${fb.strengths.map((s) => `<li>${esc(s)}</li>`).join('')}</ul><p><b>Improve</b></p><ul>${fb.improvements.map((s) => `<li>${esc(s)}</li>`).join('')}</ul><p><b>Sample answer</b><br>${esc(fb.sample_answer)}</p>` : ''}
${resume ? `<h2>Improved resume</h2><pre style="white-space:pre-wrap;font-family:inherit">${esc(resumeToMarkdown(resume))}</pre>` : ''}
<script>setTimeout(()=>print(),300)</script></body></html>`)
  w.document.close()
  return true
}
